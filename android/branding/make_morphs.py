#!/usr/bin/env python3
"""Generates the morphing toggle icons from the static Geist glyphs they join.

Each end of a morph is exactly the static drawable shown before and after the toggle
(ic_tv_check / ic_tv_unwatched, ic_tv_heart_outline / ic_tv_heart), so a played morph
leaves the same picture the next page draws. Android only interpolates path data with
the same commands, so both ends are rebuilt as matching absolute cubic segments.

Usage, from android/:  python3 branding/make_morphs.py
Standard library only; writes app/src/main/res/drawable/avd_tv_*.xml.
"""
import math
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res", "drawable")
HEADER = "<!-- Generated by branding/make_morphs.py; regenerate rather than hand-edit. -->\n"


def arc(p0, rx, ry, phi, large, sweep, p1):
    """SVG endpoint arc as cubic segments of at most 90 degrees (SVG 1.1 F.6.5)."""
    (x1, y1), (x2, y2) = p0, p1
    phi = math.radians(phi)
    c, s = math.cos(phi), math.sin(phi)
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    xp, yp = c * dx + s * dy, -s * dx + c * dy
    lam = (xp * xp) / (rx * rx) + (yp * yp) / (ry * ry)
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx * rx * ry * ry - rx * rx * yp * yp - ry * ry * xp * xp
    den = rx * rx * yp * yp + ry * ry * xp * xp
    k = math.sqrt(max(0.0, num / den)) * (-1 if large == sweep else 1)
    cxp, cyp = k * rx * yp / ry, -k * ry * xp / rx
    cx, cy = c * cxp - s * cyp + (x1 + x2) / 2, s * cxp + c * cyp + (y1 + y2) / 2

    def angle(ux, uy, vx, vy):
        a = math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
        return a

    t1 = angle(1, 0, (xp - cxp) / rx, (yp - cyp) / ry)
    dt = angle((xp - cxp) / rx, (yp - cyp) / ry, (-xp - cxp) / rx, (-yp - cyp) / ry)
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    n = max(1, int(math.ceil(abs(dt) / (math.pi / 2) - 1e-9)))
    step = dt / n
    alpha = 4 / 3 * math.tan(step / 4)
    out = []
    for i in range(n):
        a, b = t1 + i * step, t1 + (i + 1) * step

        def point(t):
            return (cx + rx * math.cos(t) * c - ry * math.sin(t) * s, cy + rx * math.cos(t) * s + ry * math.sin(t) * c)

        def deriv(t):
            return (-rx * math.sin(t) * c - ry * math.cos(t) * s, -rx * math.sin(t) * s + ry * math.cos(t) * c)

        pa, pb, da, db = point(a), point(b), deriv(a), deriv(b)
        out.append(((pa[0] + alpha * da[0], pa[1] + alpha * da[1]), (pb[0] - alpha * db[0], pb[1] - alpha * db[1]), pb))
    out[-1] = (out[-1][0], out[-1][1], p1)
    return out


def line(p0, p1):
    return [((p0[0] + (p1[0] - p0[0]) / 3, p0[1] + (p1[1] - p0[1]) / 3), (p0[0] + 2 * (p1[0] - p0[0]) / 3, p0[1] + 2 * (p1[1] - p0[1]) / 3), p1)]


def split(p0, seg):
    """de Casteljau halves of a cubic starting at p0."""
    c1, c2, p1 = seg
    mid = lambda a, b: ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
    a, b, c = mid(p0, c1), mid(c1, c2), mid(c2, p1)
    d, e = mid(a, b), mid(b, c)
    f = mid(d, e)
    return [(a, d, f), (e, c, p1)]


def length(p0, seg):
    pts = [p0, *seg]
    return sum(math.dist(pts[i], pts[i + 1]) for i in range(3))


def segments(sub, count):
    """Splits the longest segments of one subpath (start, [cubics]) until it has `count`."""
    start, segs = sub
    segs = list(segs)
    while len(segs) < count:
        starts = [start] + [s[2] for s in segs[:-1]]
        i = max(range(len(segs)), key=lambda j: length(starts[j], segs[j]))
        segs[i:i + 1] = split(starts[i], segs[i])
    return start, segs


def point(p):
    return (p, [])


def path(subs):
    def n(v):
        text = ("%.3f" % v).rstrip("0").rstrip(".")
        return "0" if text in ("-0", "") else text

    out = []
    for start, segs in subs:
        out.append("M%s,%s" % (n(start[0]), n(start[1])))
        for c1, c2, p in segs:
            out.append("C%s,%s %s,%s %s,%s" % tuple(n(v) for v in (*c1, *c2, *p)))
    return " ".join(out)


def matched(a, b):
    """Two subpath lists with equal segment counts, pairwise."""
    out_a, out_b = [], []
    for sa, sb in zip(a, b):
        count = max(len(sa[1]), len(sb[1]), 1)
        if not sa[1]:
            sa = (sa[0], [(sa[0], sa[0], sa[0])])
        if not sb[1]:
            sb = (sb[0], [(sb[0], sb[0], sb[0])])
        out_a.append(segments(sa, count))
        out_b.append(segments(sb, count))
    return path(out_a), path(out_b)


# ic_tv_unwatched (Geist eye-off), as absolute cubics: the lower lid, the upper lid and the pupil.
EYE = [
    ((17.94, 17.94), arc((17.94, 17.94), 10.07, 10.07, 0, 0, 1, (12, 20)) + [((5, 20), (1, 12), (1, 12))]
     + arc((1, 12), 18.45, 18.45, 0, 0, 1, (6.06, 6.06))),
    ((9.9, 4.24), arc((9.9, 4.24), 9.12, 9.12, 0, 0, 1, (12, 4)) + [((19, 4), (23, 12), (23, 12))]
     + arc((23, 12), 18.5, 18.5, 0, 0, 1, (20.84, 15.19))),
    ((14.12, 14.12), arc((14.12, 14.12), 3, 3, 0, 1, 1, (9.88, 9.88))),
]
# ic_tv_check: the whole tick becomes the lower lid; the upper lid and pupil grow out of points on its long stroke,
# where their round-capped dots stay hidden under the tick.
CHECK = [
    ((20, 6), line((20, 6), (9, 17)) + line((9, 17), (4, 12))),
    point((16, 10)),
    point((12, 14)),
]
STROKE = ('android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" '
          'android:strokeLineCap="round" android:strokeLineJoin="round"')
HEART = ("M20.84,4.61 a5.5,5.5,0,0,0,-7.78,0 L12,5.67 l-1.06,-1.06 a5.5,5.5,0,0,0,-7.78,7.78 l1.06,1.06 "
         "L12,21.23 l7.78,-7.78 l1.06,-1.06 a5.5,5.5,0,0,0,0,-7.78 z")
def scaled(data, k, cx=12.0, cy=12.5):
    """`data` (M/L/l/a/z only) scaled by k about (cx, cy): absolute points about it, relative ones and radii by k."""
    def n(v):
        text = ("%.4f" % v).rstrip("0").rstrip(".")
        return "0" if text in ("-0", "") else text

    out = []
    for token in data.split(" "):
        command, values = token[0], [float(v) for v in token[1:].split(",")] if len(token) > 1 else []
        if command in "ML":
            values = [cx + (values[0] - cx) * k, cy + (values[1] - cy) * k]
        elif command == "l":
            values = [v * k for v in values]
        elif command == "a":
            values = [values[0] * k, values[1] * k, values[2], values[3], values[4], values[5] * k, values[6] * k]
        out.append(command + ",".join(n(v) if i not in (2, 3, 4) or command != "a" else str(int(v)) for i, v in enumerate(values)))
    return " ".join(out)


# The filled heart grows from its centre: the same commands at 1% of the size.
HEART_SEED = scaled(HEART, 0.01)


def vector(body):
    return ('    <aapt:attr name="android:drawable">\n'
            '        <vector android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            + body +
            '        </vector>\n'
            '    </aapt:attr>\n')


def target(name, animators):
    return ('    <target android:name="%s">\n        <aapt:attr name="android:animation">\n            <set>\n%s            </set>\n'
            '        </aapt:attr>\n    </target>\n') % (name, animators)


def animator(prop, start, end, duration, kind="floatType", delay=0, interpolator="@android:interpolator/fast_out_slow_in"):
    return ('                <objectAnimator android:propertyName="%s" android:valueFrom="%s" android:valueTo="%s"\n'
            '                    android:valueType="%s" android:duration="%d" android:startOffset="%d"\n'
            '                    android:interpolator="%s" />\n') % (prop, start, end, kind, duration, delay, interpolator)


def avd(comment, body, targets):
    return ('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER + "<!-- " + comment + " -->\n"
            '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt">\n' + vector(body) + "".join(targets) + "</animated-vector>\n")


def watched(on):
    check, eye = matched(CHECK, EYE)
    start, end = (check, eye) if on else (eye, check)
    body = ('            <path android:name="eye" %s\n                android:pathData="%s" />\n'
            '            <path android:name="slash" %s android:trimPathEnd="%s"\n                android:pathData="M1,1 L23,23" />\n'
            % (STROKE, start, STROKE, "0" if on else "1"))
    duration = 320 if on else 260
    return avd("Mark watched: the tick opens into the struck-out eye of Mark unwatched." if on else
               "Mark unwatched: the struck-out eye folds back into the tick of Mark watched.", body, [
        target("eye", animator("pathData", start, end, duration, "pathType")),
        target("slash", animator("trimPathEnd", "0" if on else "1", "1" if on else "0", 200,
                                 delay=duration - 200 if on else 0)),
    ])


def favourite(on):
    seed, full = (HEART_SEED, HEART) if on else (HEART, HEART_SEED)
    body = ('            <group android:name="pop" android:pivotX="12" android:pivotY="12.5">\n'
            '                <path android:name="fill" android:fillColor="#FFFFFFFF"\n                    android:pathData="%s" />\n'
            '                <path android:name="rim" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="%s"\n'
            '                    android:strokeLineCap="round" android:strokeLineJoin="round"\n                    android:pathData="%s" />\n'
            '            </group>\n' % (seed, "2" if on else "1.5", HEART))
    targets = [
        target("fill", animator("pathData", seed, full, 300 if on else 220, "pathType")),
        target("rim", animator("strokeWidth", "2" if on else "1.5", "1.5" if on else "2", 300 if on else 220)),
    ]
    if on:
        pop = (animator("scaleX", "1", "1.18", 140, interpolator="@android:interpolator/decelerate_quad")
               + animator("scaleY", "1", "1.18", 140, interpolator="@android:interpolator/decelerate_quad")
               + animator("scaleX", "1.18", "1", 220, delay=140)
               + animator("scaleY", "1.18", "1", 220, delay=140))
        targets.append(target("pop", pop))
    return avd("Add favourite: the outline fills from its centre with a small beat." if on else
               "Remove favourite: the fill drains to the heart's centre, leaving the outline.", body, targets)


def main():
    assert scaled(HEART, 1) == HEART, scaled(HEART, 1)
    files = {
        "avd_tv_watched_on.xml": watched(True),
        "avd_tv_watched_off.xml": watched(False),
        "avd_tv_favourite_on.xml": favourite(True),
        "avd_tv_favourite_off.xml": favourite(False),
    }
    for name, text in files.items():
        with open(os.path.join(OUT, name), "w") as f:
            f.write(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
